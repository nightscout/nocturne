using Aspire.Hosting;
using Aspire.Hosting.ApplicationModel;
using FluentAssertions;
using Nocturne.Aspire.Host.Publishing;
using Xunit;

namespace Nocturne.Aspire.Host.Tests.Publishing;

public class InstallScriptsTests
{
    private static readonly string[] Secrets = ["INSTANCE_KEY", "POSTGRES_PASSWORD"];

    private static readonly Dictionary<string, string> Sources = new()
    {
        ["install.sh"] = "#!/usr/bin/env bash\nGENERATED_SECRETS=(@@GENERATED_SECRETS@@)\necho install\n",
        ["oracle-cloud-install.sh"] =
            "#!/usr/bin/env bash\ncat <<'NOCTURNE_EMBED_EOF'\n#@embed install.sh\nNOCTURNE_EMBED_EOF\n"
            + "cat <<'NOCTURNE_EMBED_EOF'\n#@embed extra.py\nNOCTURNE_EMBED_EOF\necho oracle\n",
        ["extra.py"] = "print('extra')\n",
    };

    private static RenderedInstallScripts Render(
        Dictionary<string, string>? sources = null,
        IReadOnlyList<string>? secrets = null)
        => InstallScripts.Render(name => (sources ?? Sources)[name], secrets ?? Secrets);

    [Fact]
    public void TheInstallerGeneratesTheSecretsItIsGiven()
    {
        Render().Install.Should().Contain("GENERATED_SECRETS=(INSTANCE_KEY POSTGRES_PASSWORD)\n");
    }

    [Fact]
    public void BothScriptsStillStartWithTheShebang()
    {
        var scripts = Render();

        scripts.Install.Should().StartWith("#!/usr/bin/env bash\n# GENERATED by ");
        scripts.OracleCloud.Should().StartWith("#!/usr/bin/env bash\n# GENERATED by ");
    }

    [Fact]
    public void TheOracleScriptHoldsTheInstallerAsReleased()
    {
        var scripts = Render();

        scripts.OracleCloud.Should().Contain(
            "cat <<'NOCTURNE_EMBED_EOF'\n" + scripts.Install + "NOCTURNE_EMBED_EOF\n");
        scripts.OracleCloud.Should().Contain("print('extra')\nNOCTURNE_EMBED_EOF\necho oracle\n");
        scripts.OracleCloud.Should().NotContain("#@embed");
    }

    [Fact]
    public void SourcesCheckedOutWithWindowsLineEndingsRenderTheSame()
    {
        var windows = Sources.ToDictionary(source => source.Key, source => source.Value.Replace("\n", "\r\n"));

        Render(windows).Should().Be(Render());
    }

    [Fact]
    public void AnInstallerWithNoPlaceForTheSecretsIsRefused()
    {
        var sources = new Dictionary<string, string>(Sources) { ["install.sh"] = "#!/usr/bin/env bash\n" };

        var render = () => Render(sources);

        render.Should().Throw<InvalidOperationException>().WithMessage("*@@GENERATED_SECRETS@@*");
    }

    [Fact]
    public void AModelWithNoSecretsIsRefused()
    {
        var render = () => Render(secrets: []);

        render.Should().Throw<InvalidOperationException>().WithMessage("*no secret parameter*");
    }

    [Fact]
    public void AnEmbeddedFileThatWouldEndItsHeredocIsRefused()
    {
        var sources = new Dictionary<string, string>(Sources) { ["extra.py"] = "NOCTURNE_EMBED_EOF\n" };

        var render = () => Render(sources);

        render.Should().Throw<InvalidOperationException>().WithMessage("*extra.py*heredoc*");
    }

    [Fact]
    public void FilesTooLargeForOracleUserDataAreRefused()
    {
        // Random text does not compress, so this is over the limit however it is packed.
        var random = new Random(1);
        var noise = string.Concat(Enumerable.Range(0, 40_000).Select(_ => (char)random.Next('a', 'z' + 1)));
        var sources = new Dictionary<string, string>(Sources) { ["extra.py"] = noise + "\n" };

        var render = () => Render(sources);

        render.Should().Throw<InvalidOperationException>().WithMessage("*user-data limit*");
    }

    [Fact]
    public void TheGeneratedSecretsAreTheSecretParametersADeploymentFormShows()
    {
        var builder = DistributedApplication.CreateBuilder();
        builder.AddParameter("zeta-key", secret: true).WithPublishMetadata("Zeta key");
        builder.AddParameter("alpha-password", secret: true).WithPublishMetadata("Alpha password");
        builder.AddParameter("base-domain", "").WithPublishMetadata("Base domain");
        builder.AddParameter("discord-bot-token", "", secret: true);
        using var app = builder.Build();

        var secrets = InstallScripts.GeneratedSecrets(
            app.Services.GetService(typeof(DistributedApplicationModel)) as DistributedApplicationModel
                ?? throw new InvalidOperationException("no model"));

        secrets.Should().Equal("ALPHA_PASSWORD", "ZETA_KEY");
    }

    [Fact]
    public void TheShippedOracleScriptHoldsTheShippedInstaller()
    {
        var root = RepositoryRoot();
        var install = File.ReadAllText(Path.Combine(root, "deploy", "install", "install.sh")).ReplaceLineEndings("\n");
        var oracle = File.ReadAllText(Path.Combine(root, "deploy", "oracle-cloud", "oracle-cloud-install.sh"))
            .ReplaceLineEndings("\n");

        oracle.Should().Contain(install);
        install.Should().NotContain("@@");
        install.Should().Contain("POSTGRES_APP_PASSWORD").And.Contain("INSTANCE_KEY");
    }

    private static string RepositoryRoot()
    {
        var directory = new DirectoryInfo(AppContext.BaseDirectory);
        while (directory is not null)
        {
            if (Directory.Exists(Path.Combine(directory.FullName, "deploy", "docker-compose")))
                return directory.FullName;
            directory = directory.Parent;
        }

        throw new InvalidOperationException("Repository root not found above " + AppContext.BaseDirectory);
    }
}
