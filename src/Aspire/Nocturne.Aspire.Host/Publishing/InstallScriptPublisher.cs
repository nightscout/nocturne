using System.IO.Compression;
using System.Text;
using Aspire.Hosting;
using Aspire.Hosting.ApplicationModel;
using Aspire.Hosting.Pipelines;
using Aspire.Hosting.Publishing;
using Microsoft.Extensions.DependencyInjection;
using Microsoft.Extensions.Logging;

namespace Nocturne.Aspire.Host.Publishing;

public static class InstallScriptPublisherExtensions
{
    /// <summary>
    /// Registers a publish pipeline step that emits <c>install.sh</c>, the installer for any
    /// Linux server, and <c>oracle-cloud-install.sh</c>, which holds that file whole and adds
    /// the Oracle Cloud provisioning around it. Both come from the sources in the AppHost's
    /// <c>install</c> directory; the secrets the installer generates come from the model.
    /// </summary>
    public static IDistributedApplicationBuilder AddInstallScriptPublisher(
        this IDistributedApplicationBuilder builder)
    {
        var sourceDirectory = Path.Combine(builder.AppHostDirectory, "install");

        builder.Pipeline.AddStep(
            name: "install-scripts",
            action: async ctx =>
            {
                var outputService = ctx.Services.GetRequiredService<IPipelineOutputService>();
                var outputPath = outputService.GetOutputDirectory();

                var scripts = InstallScripts.Render(
                    name => File.ReadAllText(Path.Combine(sourceDirectory, name)),
                    InstallScripts.GeneratedSecrets(ctx.Model));

                await File.WriteAllTextAsync(
                    Path.Combine(outputPath, InstallScripts.InstallScriptName),
                    scripts.Install,
                    ctx.CancellationToken);
                await File.WriteAllTextAsync(
                    Path.Combine(outputPath, InstallScripts.OracleScriptName),
                    scripts.OracleCloud,
                    ctx.CancellationToken);

                ctx.Logger.LogInformation(
                    "[install-scripts] Wrote {Install} and {Oracle}",
                    InstallScripts.InstallScriptName,
                    InstallScripts.OracleScriptName);
            },
            dependsOn: "publish-compose",
            requiredBy: WellKnownPipelineSteps.Publish);

        return builder;
    }
}

internal sealed record RenderedInstallScripts(string Install, string OracleCloud);

internal static class InstallScripts
{
    public const string InstallScriptName = "install.sh";
    public const string OracleScriptName = "oracle-cloud-install.sh";

    private const string SecretsPlaceholder = "@@GENERATED_SECRETS@@";
    private const string EmbedDirective = "#@embed ";
    private const string HeredocDelimiter = "NOCTURNE_EMBED_EOF";

    private const string GeneratedNotice =
        "# GENERATED by scripts/publish-release.cs from src/Aspire/Nocturne.Aspire.Host/install.\n"
        + "# Do not edit this copy by hand.\n";

    /// <summary>Oracle refuses user-data over this many bytes once it is base64-encoded.</summary>
    private const int OracleUserDataLimit = 16384;

    /// <summary>
    /// Room for what the Oracle script adds to its cloud-init at run time: the YAML around the
    /// embedded files, install.env and the systemd unit.
    /// </summary>
    private const int OracleUserDataReserve = 2048;

    /// <summary>
    /// The variables the installer fills with a random value: every secret parameter that a
    /// deployment form shows, which is what carries an <see cref="EnvVarMetadataAnnotation"/>.
    /// </summary>
    public static IReadOnlyList<string> GeneratedSecrets(DistributedApplicationModel model)
        => [.. model.Resources
            .OfType<ParameterResource>()
            .Where(parameter => parameter.Secret
                && parameter.Annotations.OfType<EnvVarMetadataAnnotation>().Any())
            .Select(parameter => parameter.Name.ToUpperInvariant().Replace("-", "_"))
            .Order(StringComparer.Ordinal)];

    public static RenderedInstallScripts Render(
        Func<string, string> readSource,
        IReadOnlyList<string> generatedSecrets)
    {
        if (generatedSecrets.Count == 0)
            throw new InvalidOperationException(
                "[install-scripts] The model has no secret parameter with publish metadata, so the installer would generate no keys.");

        string Read(string name) => readSource(name).ReplaceLineEndings("\n");

        var installSource = Read(InstallScriptName);
        if (!installSource.Contains(SecretsPlaceholder, StringComparison.Ordinal))
            throw new InvalidOperationException(
                $"[install-scripts] {InstallScriptName} does not contain {SecretsPlaceholder}.");

        var install = WithNotice(
            installSource.Replace(SecretsPlaceholder, string.Join(' ', generatedSecrets), StringComparison.Ordinal));

        var embedded = new StringBuilder();
        var oracle = new StringBuilder();
        foreach (var line in Read(OracleScriptName).Split('\n'))
        {
            if (!line.StartsWith(EmbedDirective, StringComparison.Ordinal))
            {
                oracle.Append(line).Append('\n');
                continue;
            }

            var name = line[EmbedDirective.Length..].Trim();
            var content = name == InstallScriptName ? install : Read(name);
            if (content.Contains(HeredocDelimiter, StringComparison.Ordinal))
                throw new InvalidOperationException(
                    $"[install-scripts] {name} contains {HeredocDelimiter}, which would end the heredoc that embeds it.");

            oracle.Append(content.TrimEnd('\n')).Append('\n');
            embedded.Append(content);
        }

        // The trailing newline the split left after the last line.
        oracle.Length--;

        if (embedded.Length == 0)
            throw new InvalidOperationException(
                $"[install-scripts] {OracleScriptName} embeds nothing; it must embed {InstallScriptName}.");

        var userData = EncodedGzipLength(embedded.ToString());
        if (userData + OracleUserDataReserve > OracleUserDataLimit)
            throw new InvalidOperationException(
                $"[install-scripts] The files {OracleScriptName} plants take {userData} bytes of Oracle's {OracleUserDataLimit}-byte user-data limit, which leaves under {OracleUserDataReserve} for the rest of its cloud-init.");

        return new RenderedInstallScripts(install, WithNotice(oracle.ToString()));
    }

    /// <summary>After the shebang, so the file still starts with it.</summary>
    private static string WithNotice(string script)
    {
        var firstLineEnd = script.IndexOf('\n') + 1;
        return script[..firstLineEnd] + GeneratedNotice + script[firstLineEnd..];
    }

    /// <summary>The base64 length of the text once gzipped, which is how the Oracle script sends it.</summary>
    private static int EncodedGzipLength(string text)
    {
        using var compressed = new MemoryStream();
        using (var gzip = new GZipStream(compressed, CompressionLevel.SmallestSize, leaveOpen: true))
            gzip.Write(Encoding.UTF8.GetBytes(text));
        return (int)((compressed.Length + 2) / 3 * 4);
    }
}
